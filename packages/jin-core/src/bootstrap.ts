import { JinError } from "./error"
import { saveArchDir } from "./model"
import type { Project } from "./project"
import { scanProject, type ScanReport } from "./scan"
import type { Arch } from "./types"
import { validateArch, type Issue } from "./validate"

export interface BootstrapOptions {
  languages?: readonly string[]
  force?: boolean
  header?: string
}

export interface BootstrapResult {
  arch: Arch
  report: ScanReport
  issues: Issue[]
  path: string
}

/** Scan an existing codebase and write its initial L0/L1 draft. Existing architectures are never overwritten by default. */
export function bootstrapProject(project: Project, options: BootstrapOptions = {}): BootstrapResult {
  if (project.hasArch() && !options.force) {
    throw new JinError(`${project.archDir}/L0.yaml 已存在。要覆盖请显式设置 force`)
  }

  const { arch, report } = scanProject(project, options.languages ? [...options.languages] : undefined)
  if (!arch.l0.modules.length) {
    throw new JinError("没有扫描到任何源码。检查 jin.yaml 的 scan.roots，或用 languages 指定语言")
  }

  saveArchDir(arch, project.archDir, options.header ?? "generated by jin bootstrap — 请审校补全 responsibility 与粒度")

  return { arch, report, issues: validateArch(arch), path: project.archDir }
}
